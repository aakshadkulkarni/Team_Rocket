const personas = [
  {
    id: "P1",
    name: "Budget-Conscious Buyer",
    profile: "Price-sensitive; compares alternatives and total value",
    weight: 0.3
  },
  {
    id: "P2",
    name: "Quality-Focused Professional",
    profile: "Prioritizes reliability, durability and performance",
    weight: 0.25
  },
  {
    id: "P3",
    name: "Sustainability-Minded Consumer",
    profile: "Looks for repairability, material transparency and environmental impact",
    weight: 0.2
  },
  {
    id: "P4",
    name: "Trend and Convenience Seeker",
    profile: "Values ease of use, design and fit with current routines",
    weight: 0.25
  }
];

export function createDemoAnalysis(product) {
  const price = Number(product.price);
  const descriptionLength = String(product.description).trim().length;
  const pricePlausible = Number.isFinite(price) && price > 0;
  const contextAdequate = descriptionLength >= 35 && String(product.targetAudience).trim().length >= 4;

  const personasOut = personas.map((p, index) => {
    const base = [3.2, 3.8, 3.4, 3.6][index];
    const pricePenalty = price > 3000 ? [0.8, 0.1, 0.2, 0.4][index] : 0;
    const contextBonus = contextAdequate ? 0.2 : -0.3;
    const score = Math.max(1, Math.min(5, Number((base - pricePenalty + contextBonus).toFixed(1))));
    return {
      id: p.id,
      name: p.name,
      profile: p.profile,
      preferenceScore: score,
      purchaseIntent: score >= 3.5 ? "Moderate" : "Low to moderate",
      sentiment: score >= 3.7 ? "Positive" : score >= 3.1 ? "Mixed" : "Cautious",
      rationale: [
        `Illustrative reaction to the stated ${product.category} product context.`,
        price > 3000 && index === 0 ? "The stated price may create a value-for-money concern." : "The description would need evidence of the claimed benefits.",
        contextAdequate ? "The product description provides some context for a preliminary reaction." : "More concrete features and use cases are needed."
      ].join(" ")
    };
  });

  const mean = personasOut.reduce((sum, p) => sum + p.preferenceScore, 0) / personasOut.length;
  const concerns = [];
  if (!contextAdequate) concerns.push("Add specific features, use cases, and differentiators to reduce ambiguity.");
  if (price > 3000) concerns.push("Test willingness to pay at multiple price points with real target customers.");
  concerns.push("Check durability, safety, usability, and competitor alternatives with appropriate evidence.");

  let verdict = "NEEDS IMPROVEMENT";
  if (pricePlausible && contextAdequate && mean >= 3.6) verdict = "PASS";
  else if (!pricePlausible || mean < 3.0) verdict = "FAIL";

  return {
    product: { name: product.name, category: product.category, price: product.price },
    verdict,
    overallPreferenceScore: Number(mean.toFixed(2)),
    scoreScale: "1–5 illustrative preference score; not a measured probability",
    summary: "This is a deterministic demo used to test the interface and report flow. It does not inspect the image or use an AI model.",
    personas: personasOut,
    strengths: [
      "The product concept can be assessed against several decision perspectives.",
      "Explicit target-audience and use-case details make later research more testable."
    ],
    improvementIdeas: concerns,
    researchCaveats: [
      "These scores are generated by illustrative rules, not real respondents.",
      "The uploaded image is not interpreted in Demo Simulation mode.",
      "No market demand, product safety, or commercial success is established."
    ],
    recommendedNextSteps: [
      "Run a small pilot survey with the intended target audience.",
      "Use a consistent 1–5 preference scale and record purchase intent separately.",
      "Compare model predictions with paired real observations before claiming predictive accuracy."
    ]
  };
}
